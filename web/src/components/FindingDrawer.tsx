import {
  AlertTriangle,
  Check,
  CheckCircle2,
  Copy,
  Download,
  ExternalLink,
  FileText,
  Scale,
  ShieldCheck,
  X,
  XCircle,
} from 'lucide-react';
import { useEffect, useState } from 'react';
import { api } from '../api/client';
import { Link } from '../router';
import type { FindingItem, RtiDraft } from '../types';
import {
  METHODOLOGY_DESCRIPTIONS,
  copyToClipboard,
  downloadTextFile,
  formatInr,
  formatRelativeTime,
  providerBadgeClass,
  statusMeta,
} from '../utils';
import { useToast } from './Toast';

interface FindingDrawerProps {
  findingId: string | number | null;
  onClose: () => void;
  onRtiCreated?: () => void;
}

export function FindingDrawer({ findingId, onClose, onRtiCreated }: FindingDrawerProps) {
  const [finding, setFinding] = useState<FindingItem | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [rtiDraft, setRtiDraft] = useState<RtiDraft | null>(null);
  const [rtiLoading, setRtiLoading] = useState(false);
  const [rtiAuthority, setRtiAuthority] = useState('');
  const [copiedKey, setCopiedKey] = useState<string | null>(null);
  const toast = useToast();

  useEffect(() => {
    if (findingId == null) return;
    let cancelled = false;
    setLoading(true);
    setError(null);
    setFinding(null);
    setRtiDraft(null);
    api
      .getFindingDetail(findingId)
      .then((data) => {
        if (cancelled) return;
        setFinding(data);
        setRtiDraft(data.rti_draft ?? null);
        setRtiAuthority(data.rti_draft?.public_authority || data.entity_name || '');
      })
      .catch((err) => {
        if (!cancelled) setError(err instanceof Error ? err.message : 'Failed to load dossier');
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });

    const onEsc = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', onEsc);
    return () => {
      cancelled = true;
      window.removeEventListener('keydown', onEsc);
    };
  }, [findingId, onClose]);

  if (findingId == null) return null;

  const handleCopy = async (key: string, text: string, label: string) => {
    const ok = await copyToClipboard(text);
    if (ok) {
      setCopiedKey(key);
      toast(label);
      window.setTimeout(() => setCopiedKey(null), 2000);
    }
  };

  const handleGenerateRti = async () => {
    if (!finding) return;
    setRtiLoading(true);
    try {
      const draft = await api.generateRtiDraft(finding.id, rtiAuthority.trim() || undefined);
      setRtiDraft(draft);
      toast(`Generated RTI Act 2005 Sec 6(1) draft (${draft.word_count} words)`);
      onRtiCreated?.();
    } catch (err) {
      toast(err instanceof Error ? err.message : 'Could not generate RTI draft');
    } finally {
      setRtiLoading(false);
    }
  };

  const handleDownloadRti = () => {
    if (!rtiDraft || !finding) return;
    const content = [
      `APPLICATION UNDER SECTION 6(1) OF THE RIGHT TO INFORMATION ACT, 2005`,
      `Public Authority: ${rtiDraft.public_authority}`,
      `CPIO: ${rtiDraft.cpio_designation}`,
      `Filing Portal: ${rtiDraft.rti_portal_url}`,
      `Statutory Sections: ${rtiDraft.statutory_sections.join(', ')}`,
      `Subject: ${rtiDraft.subject}`,
      `Word Count: ${rtiDraft.word_count} / 500`,
      `Finding Reference: ${finding.id} (${finding.methodology_code})`,
      `--------------------------------------------------------------------`,
      '',
      rtiDraft.body_text,
      '',
      `--------------------------------------------------------------------`,
      `Note: Generated by AI Watchdogs India (aiwatchdogs.in) as a citizen draft.`,
      `Review carefully and file personally via https://rtionline.gov.in/ (₹10 fee; BPL exempt under Sec 7(5)).`,
    ].join('\n');
    downloadTextFile(`rti-draft-${finding.id}.txt`, content);
    toast('Downloaded RTI draft (.txt)');
  };

  const sm = finding ? statusMeta(finding.status) : null;
  const confirmCount =
    finding?.confirm_count ??
    finding?.verifications?.filter((v) => v.verdict === 'confirm').length ??
    0;
  const requiredQuorum = finding?.required_quorum ?? 2;
  const methodMeta = finding ? METHODOLOGY_DESCRIPTIONS[finding.methodology_code] : null;

  return (
    <div
      className="overlay-backdrop"
      role="dialog"
      aria-modal="true"
      aria-label="Evidence Dossier"
      onClick={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
    >
      <div className="drawer-panel">
        <div className="overlay-header">
          <div style={{ minWidth: 0 }}>
            <div style={{ display: 'flex', alignItems: 'center', gap: 7, flexWrap: 'wrap', marginBottom: 6 }}>
              <span className="font-mono" style={{ fontSize: 11, color: 'var(--ink-muted)' }}>
                EVIDENCE DOSSIER #{String(findingId)}
              </span>
              {sm && <span className={sm.badgeClass}>{sm.label}</span>}
              {finding && <span className="tag-mono tag-method">{finding.methodology_code}</span>}
            </div>
            <h2
              className="font-serif"
              style={{ margin: 0, fontSize: 22, lineHeight: 1.24, fontWeight: 600 }}
            >
              {loading ? 'Loading evidence dossier…' : finding?.title || 'Finding Dossier'}
            </h2>
          </div>

          <button
            type="button"
            className="btn btn-ghost btn-sm"
            onClick={onClose}
            aria-label="Close dossier"
          >
            <X size={16} />
          </button>
        </div>

        <div className="overlay-body">
          {loading && (
            <div className="state-banner">Loading deterministic metrics, provenance hashes, and peer quorum…</div>
          )}

          {error && (
            <div className="state-banner" style={{ borderColor: 'var(--ep-disputed-bd)', color: 'var(--ep-disputed-fg)' }}>
              Could not load finding dossier: {error}
            </div>
          )}

          {finding && (
            <>
              {/* Key Metadata Strip */}
              <div className="card card-pad-sm">
                <div className="grid-4" style={{ gap: 12 }}>
                  <div>
                    <div className="font-mono" style={{ fontSize: 10.5, color: 'var(--ink-muted)', textTransform: 'uppercase' }}>
                      Public Entity
                    </div>
                    <div style={{ fontWeight: 600, fontSize: 13.5, marginTop: 2 }}>{finding.entity_name}</div>
                  </div>
                  <div>
                    <div className="font-mono" style={{ fontSize: 10.5, color: 'var(--ink-muted)', textTransform: 'uppercase' }}>
                      Jurisdiction / FY
                    </div>
                    <div style={{ fontSize: 13.5, marginTop: 2 }}>
                      {finding.jurisdiction} · <span className="font-mono">{finding.fiscal_year}</span>
                    </div>
                  </div>
                  <div>
                    <div className="font-mono" style={{ fontSize: 10.5, color: 'var(--ink-muted)', textTransform: 'uppercase' }}>
                      Quantified Exposure
                    </div>
                    <div className="font-mono tabular" style={{ fontWeight: 600, fontSize: 15, marginTop: 2 }}>
                      {finding.monetary_exposure_inr ? formatInr(finding.monetary_exposure_inr) : 'Disclosure Lead'}
                    </div>
                  </div>
                  <div>
                    <div className="font-mono" style={{ fontSize: 10.5, color: 'var(--ink-muted)', textTransform: 'uppercase' }}>
                      Severity / Quorum
                    </div>
                    <div className="font-mono tabular" style={{ fontSize: 13.5, marginTop: 2 }}>
                      <span className={`sev-${finding.severity}`}>{finding.severity.toUpperCase()}</span>
                      {' · '}
                      <strong>{confirmCount}/{requiredQuorum}</strong>
                    </div>
                  </div>
                </div>
              </div>

              {/* Neutral Editorial Summary */}
              <div className="card card-pad">
                <div className="section-kicker">Factual Public-Record Summary</div>
                <p style={{ margin: '6px 0 10px', fontSize: 14, lineHeight: 1.6, color: 'var(--ink-secondary)' }}>
                  {finding.summary}
                </p>
                <div style={{ display: 'flex', gap: 10, flexWrap: 'wrap', fontSize: 12, color: 'var(--ink-muted)' }}>
                  {methodMeta && (
                    <span>
                      <strong>Rule:</strong> {methodMeta.name} ({methodMeta.rule})
                    </span>
                  )}
                  {finding.rule_triggered && (
                    <span className="tag-mono">Triggered: {finding.rule_triggered}</span>
                  )}
                </div>
              </div>

              {/* Deterministic Metrics Table */}
              {Object.keys(finding.anomaly_metrics).length > 0 && (
                <div>
                  <div
                    style={{
                      display: 'flex',
                      justifyContent: 'space-between',
                      alignItems: 'center',
                      marginBottom: 8,
                      gap: 10,
                      flexWrap: 'wrap',
                    }}
                  >
                    <div className="section-kicker" style={{ marginBottom: 0 }}>
                      Deterministic Computed Metrics (Reproducible)
                    </div>
                    {finding.verifier_script_hash && (
                      <span className="font-mono" style={{ fontSize: 11, color: 'var(--ink-muted)' }}>
                        engine_sha256: {finding.verifier_script_hash.slice(0, 12)}
                      </span>
                    )}
                  </div>
                  <div className="table-wrap">
                    <table className="ledger-table">
                      <thead>
                        <tr>
                          <th>Metric</th>
                          <th className="num">Computed Value</th>
                        </tr>
                      </thead>
                      <tbody>
                        {Object.entries(finding.anomaly_metrics).map(([k, v]) => (
                          <tr key={k}>
                            <td style={{ textTransform: 'capitalize' }}>{k.replace(/_/g, ' ')}</td>
                            <td className="num">
                              {typeof v === 'number'
                                ? k.includes('inr')
                                  ? formatInr(v)
                                  : v.toLocaleString('en-IN', { maximumFractionDigits: 3 })
                                : typeof v === 'object'
                                  ? JSON.stringify(v)
                                  : String(v)}
                            </td>
                          </tr>
                        ))}
                      </tbody>
                    </table>
                  </div>
                </div>
              )}

              {/* Primary Source & Cryptographic Provenance */}
              <div className="card card-pad">
                <div className="section-kicker">Primary .gov.in Source &amp; Cryptographic Provenance</div>
                <div style={{ display: 'flex', flexDirection: 'column', gap: 10, marginTop: 8 }}>
                  {finding.source_url && (
                    <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', gap: 10, flexWrap: 'wrap' }}>
                      <a
                        href={finding.source_url}
                        target="_blank"
                        rel="noreferrer"
                        className="font-mono"
                        style={{
                          fontSize: 12.5,
                          color: 'var(--ep-rti-fg)',
                          display: 'inline-flex',
                          alignItems: 'center',
                          gap: 5,
                          wordBreak: 'break-all',
                        }}
                      >
                        <ExternalLink size={13} style={{ flexShrink: 0 }} />
                        <span>{finding.source_url}</span>
                      </a>
                    </div>
                  )}

                  {finding.artifact_sha256 && (
                    <div
                      style={{
                        display: 'flex',
                        alignItems: 'center',
                        justifyContent: 'space-between',
                        gap: 8,
                        background: 'var(--bg-sunk)',
                        padding: '8px 10px',
                        borderRadius: 4,
                        border: '1px solid var(--border-hairline)',
                      }}
                    >
                      <span className="font-mono" style={{ fontSize: 11.5, wordBreak: 'break-all' }}>
                        <strong>SHA-256:</strong> {finding.artifact_sha256}
                      </span>
                      <button
                        type="button"
                        className="btn btn-ghost btn-xs"
                        onClick={() => handleCopy('sha', finding.artifact_sha256 || '', 'Copied artifact SHA-256 hash')}
                      >
                        {copiedKey === 'sha' ? <Check size={12} /> : <Copy size={12} />}
                        <span>{copiedKey === 'sha' ? 'Copied' : 'Copy'}</span>
                      </button>
                    </div>
                  )}

                  {finding.citations.length > 0 && (
                    <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
                      <div style={{ fontSize: 12, fontWeight: 600, color: 'var(--ink-secondary)' }}>
                        Pinpoint Citations ({finding.citations.length})
                      </div>
                      {finding.citations.map((cit, i) => (
                        <div
                          key={i}
                          style={{
                            padding: '10px 12px',
                            background: 'var(--bg-paper)',
                            borderLeft: '2px solid var(--border-strong)',
                            fontSize: 12.5,
                          }}
                        >
                          <div className="font-mono" style={{ fontSize: 11, color: 'var(--ink-muted)', marginBottom: 4 }}>
                            {[
                              cit.title,
                              cit.page != null ? `Page ${cit.page}` : null,
                              cit.para ? `Para ${cit.para}` : null,
                              cit.row_id != null ? `Row ${cit.row_id}` : null,
                            ]
                              .filter(Boolean)
                              .join(' · ') || 'Primary record excerpt'}
                          </div>
                          {cit.excerpt && (
                            <div style={{ color: 'var(--ink-primary)', fontStyle: 'italic' }}>
                              “{cit.excerpt}”
                            </div>
                          )}
                        </div>
                      ))}
                    </div>
                  )}
                </div>
              </div>

              {/* Mandatory Benign Explanations Box (BNS Sec 356 Fairness) */}
              <div
                style={{
                  background: '#FBF8F1',
                  border: '1px solid var(--ep-review-bd)',
                  borderLeft: '3px solid var(--ep-review-fg)',
                  borderRadius: 4,
                  padding: '15px 18px',
                }}
              >
                <div
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    gap: 7,
                    fontSize: 12.5,
                    fontWeight: 600,
                    color: 'var(--ep-review-fg)',
                    marginBottom: 8,
                  }}
                >
                  <Scale size={14} />
                  <span>Mandatory Benign / Lawful Explanations (Journalistic Fairness · BNS Sec 356)</span>
                </div>
                <p style={{ margin: '0 0 8px', fontSize: 12.5, color: 'var(--ink-muted)' }}>
                  Statistical divergence in public records is an audit lead — never an allegation of
                  wrongdoing. Before drawing conclusions, verify these plausible lawful explanations:
                </p>
                <ul style={{ margin: 0, paddingLeft: 18, fontSize: 13, color: 'var(--ink-secondary)', display: 'flex', flexDirection: 'column', gap: 5 }}>
                  {(finding.benign_explanations.length > 0
                    ? finding.benign_explanations
                    : ['Lawful statutory exception or competent authority waiver may exist on the official file.']
                  ).map((exp, idx) => (
                    <li key={idx}>{exp}</li>
                  ))}
                </ul>
              </div>

              {/* Independent Peer Verification Quorum Tracker */}
              <div className="card card-pad">
                <div
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    justifyContent: 'space-between',
                    gap: 10,
                    marginBottom: 12,
                    flexWrap: 'wrap',
                  }}
                >
                  <div>
                    <div className="section-kicker" style={{ marginBottom: 2 }}>
                      Independent Peer Verification Quorum
                    </div>
                    <div style={{ fontSize: 13, color: 'var(--ink-muted)' }}>
                      Submitted by{' '}
                      {finding.submitted_by ? (
                        <Link
                          to={`/a/${encodeURIComponent(finding.submitted_by)}`}
                          onClick={onClose}
                          className="font-mono"
                          style={{ color: 'var(--ep-contrib-fg)', fontWeight: 600 }}
                        >
                          @{finding.submitted_by}
                        </Link>
                      ) : (
                        'swarm node'
                      )}{' '}
                      · Distinct contributor nodes must independently reproduce math &amp; provenance.
                    </div>
                  </div>
                  <span className={confirmCount >= requiredQuorum ? 'badge badge-verified' : 'badge badge-review'}>
                    <ShieldCheck size={12} />
                    <span>
                      {confirmCount}/{requiredQuorum} Confirmed
                    </span>
                  </span>
                </div>

                {finding.verifications && finding.verifications.length > 0 ? (
                  <div style={{ display: 'flex', flexDirection: 'column', gap: 10 }}>
                    {finding.verifications.map((v, i) => (
                      <div
                        key={v.id ?? i}
                        style={{
                          padding: '12px 14px',
                          background: 'var(--bg-paper)',
                          border: '1px solid var(--border-hairline)',
                          borderRadius: 4,
                        }}
                      >
                        <div
                          style={{
                            display: 'flex',
                            justifyContent: 'space-between',
                            alignItems: 'center',
                            gap: 8,
                            flexWrap: 'wrap',
                            marginBottom: 6,
                          }}
                        >
                          <div style={{ display: 'flex', alignItems: 'center', gap: 8, flexWrap: 'wrap' }}>
                            <Link
                              to={`/a/${encodeURIComponent(v.verifier_handle)}`}
                              onClick={onClose}
                              className="font-mono"
                              style={{ fontSize: 12.5, fontWeight: 600, color: 'var(--ep-contrib-fg)' }}
                            >
                              @{v.verifier_handle}
                            </Link>
                            <span className={providerBadgeClass(v.provider || v.model_id)}>
                              {v.provider ? `${v.provider} / ${v.model_id}` : v.model_id}
                            </span>
                          </div>
                          <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                            <span
                              className={
                                v.verdict === 'confirm' ? 'badge badge-verified' : 'badge badge-disputed'
                              }
                            >
                              {v.verdict.toUpperCase()}
                            </span>
                            <span className="font-mono tabular" style={{ fontSize: 11.5, color: 'var(--ink-muted)' }}>
                              {Math.round(v.confidence * 100)}% conf
                            </span>
                          </div>
                        </div>

                        <div style={{ display: 'flex', gap: 12, flexWrap: 'wrap', fontSize: 11.5, marginBottom: v.notes ? 6 : 0 }}>
                          {[
                            ['Provenance Hash', v.checks.provenance_ok],
                            ['Math Reproduced', v.checks.math_reproduced],
                            ['Rule Valid', v.checks.rule_valid],
                            ['Legal & PII Clean', v.checks.legal_pii_ok],
                          ].map(([label, ok]) => (
                            <span
                              key={String(label)}
                              style={{
                                display: 'inline-flex',
                                alignItems: 'center',
                                gap: 4,
                                color: ok ? 'var(--ep-verified-fg)' : 'var(--ep-disputed-fg)',
                              }}
                            >
                              {ok ? <CheckCircle2 size={12} /> : <XCircle size={12} />}
                              <span>{label}</span>
                            </span>
                          ))}
                        </div>

                        {v.notes && (
                          <p style={{ margin: 0, fontSize: 12.5, color: 'var(--ink-secondary)' }}>
                            {v.notes}
                          </p>
                        )}
                      </div>
                    ))}
                  </div>
                ) : (
                  <div className="state-banner" style={{ padding: 16 }}>
                    Awaiting independent peer verification from 2 distinct contributor nodes. Run{' '}
                    <code className="font-mono">aiwatchdogs join --mode verify</code> to verify this lead!
                  </div>
                )}
              </div>

              {/* 1-Click RTI Act 2005 Sec 6(1) Draft Generator & Viewer */}
              <div className="card card-pad" style={{ borderColor: 'var(--ep-rti-bd)' }}>
                <div
                  style={{
                    display: 'flex',
                    alignItems: 'flex-start',
                    justifyContent: 'space-between',
                    gap: 12,
                    flexWrap: 'wrap',
                    marginBottom: 12,
                  }}
                >
                  <div>
                    <div className="section-kicker" style={{ color: 'var(--ep-rti-fg)', marginBottom: 3 }}>
                      Lawful Citizen Action · RTI Act 2005 Section 6(1) &amp; Section 2(f)
                    </div>
                    <h3 className="font-serif" style={{ margin: 0, fontSize: 20 }}>
                      Ready-to-File Public Records Request
                    </h3>
                  </div>

                  {rtiDraft && (
                    <span
                      className={`font-mono tabular ${
                        rtiDraft.word_count <= 500 ? 'badge badge-verified' : 'badge badge-disputed'
                      }`}
                    >
                      {rtiDraft.word_count} / 500 words
                    </span>
                  )}
                </div>

                <div style={{ display: 'flex', gap: 8, flexWrap: 'wrap', marginBottom: 12 }}>
                  <input
                    type="text"
                    className="input-field"
                    style={{ flex: 1, minWidth: 220 }}
                    value={rtiAuthority}
                    onChange={(e) => setRtiAuthority(e.target.value)}
                    placeholder="Target Public Authority / Ministry (optional override)"
                    aria-label="Target Public Authority"
                  />
                  <button
                    type="button"
                    className="btn btn-rti"
                    onClick={handleGenerateRti}
                    disabled={rtiLoading}
                  >
                    <FileText size={14} />
                    <span>
                      {rtiLoading
                        ? 'Drafting…'
                        : rtiDraft
                          ? 'Regenerate RTI Draft'
                          : 'Generate RTI Act 2005 Draft'}
                    </span>
                  </button>
                </div>

                {rtiDraft ? (
                  <>
                    <div
                      style={{
                        display: 'flex',
                        justifyContent: 'space-between',
                        alignItems: 'center',
                        gap: 10,
                        flexWrap: 'wrap',
                        marginBottom: 10,
                        fontSize: 12.5,
                      }}
                    >
                      <div>
                        <strong>Authority:</strong> {rtiDraft.public_authority} ·{' '}
                        <strong>CPIO:</strong> {rtiDraft.cpio_designation}
                      </div>
                      <div style={{ display: 'flex', gap: 7 }}>
                        <button
                          type="button"
                          className="btn btn-secondary btn-xs"
                          onClick={() =>
                            handleCopy('rti', rtiDraft.body_text, 'Copied RTI Act 2005 Sec 6(1) text')
                          }
                        >
                          {copiedKey === 'rti' ? <Check size={12} /> : <Copy size={12} />}
                          <span>{copiedKey === 'rti' ? 'Copied' : 'Copy Text'}</span>
                        </button>
                        <button
                          type="button"
                          className="btn btn-secondary btn-xs"
                          onClick={handleDownloadRti}
                        >
                          <Download size={12} />
                          <span>Download .txt</span>
                        </button>
                      </div>
                    </div>

                    <div className="rti-paper">{rtiDraft.body_text}</div>

                    <div
                      style={{
                        marginTop: 12,
                        padding: '12px 14px',
                        background: 'var(--ep-rti-bg)',
                        border: '1px solid var(--ep-rti-bd)',
                        borderRadius: 4,
                        fontSize: 12.5,
                        color: 'var(--ink-secondary)',
                      }}
                    >
                      <div style={{ fontWeight: 600, color: 'var(--ep-rti-fg)', marginBottom: 4 }}>
                        Human-in-the-Loop Filing Guide (rtionline.gov.in)
                      </div>
                      <ol style={{ margin: 0, paddingLeft: 18, display: 'flex', flexDirection: 'column', gap: 3 }}>
                        <li>
                          AI agents never auto-file legal requests. Review every line above and verify
                          it seeks existing official records under Sec 2(f).
                        </li>
                        <li>
                          Open{' '}
                          <a
                            href={rtiDraft.rti_portal_url || 'https://rtionline.gov.in/'}
                            target="_blank"
                            rel="noreferrer"
                            style={{ color: 'var(--ep-rti-fg)', textDecoration: 'underline', fontWeight: 600 }}
                          >
                            rtionline.gov.in
                          </a>{' '}
                          (or the relevant State RTI portal), select the Public Authority, and paste the
                          text (strictly ≤500 words per Central RTI Rules 2012 Rule 3).
                        </li>
                        <li>
                          Pay the statutory <strong>₹10 fee</strong> (exempt for BPL applicants under
                          Section 7(5)). Statutory CPIO response deadline is <strong>30 days</strong>{' '}
                          (First Appeal under Section 19(1) if unanswered).
                        </li>
                      </ol>
                    </div>
                  </>
                ) : (
                  <div
                    style={{
                      display: 'flex',
                      alignItems: 'center',
                      gap: 8,
                      fontSize: 12.5,
                      color: 'var(--ink-muted)',
                    }}
                  >
                    <AlertTriangle size={14} />
                    <span>
                      Click <strong>Generate RTI Act 2005 Draft</strong> to produce a ≤500-word Sec 6(1)
                      records request citing this finding’s exact public artifact and statutory anchor.
                    </span>
                  </div>
                )}
              </div>

              {finding.created_at && (
                <div className="font-mono" style={{ fontSize: 11, color: 'var(--ink-faint)', textAlign: 'right' }}>
                  Logged {formatRelativeTime(finding.created_at)}
                  {finding.verified_at ? ` · Peer-Verified ${formatRelativeTime(finding.verified_at)}` : ''}
                </div>
              )}
            </>
          )}
        </div>
      </div>
    </div>
  );
}
